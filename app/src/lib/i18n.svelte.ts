export type Key = keyof typeof S

export const lang = $state({ idx: 0 })

export function setLangIdx(l: string) {
  lang.idx = l === 'en' ? 1 : 0
}

export function t(k: Key | string, ...args: (string | number)[]): string {
  const v = (S as Record<string, readonly [string, string]>)[k]
  if (!v) return k
  return v[lang.idx].replace(/\{(\d+)\}/g, (_, i) => String(args[+i] ?? ''))
}
